"""Export validated candidates as self-contained inspect_ai Docker tasks.

Each environment directory is runnable on its own with
``inspect eval task.py --model <model>`` (requires inspect-ai and Docker):

    envs/<env_id>/
      task.py       — inspect_ai task: Docker sandbox, agent solver,
                      programmatic scorer (reads checks.json at runtime)
      Dockerfile    — sandbox image (office/python document tooling)
      compose.yaml
      checks.json   — the validated reward checks
      env.json      — prompt, deliverables, provenance, validation record
      references/   — the data room, copied from the source task

The scorer never calls an LLM: it reads the agent's ``report.json`` and the
deliverable files from the sandbox and applies the checks.
"""

from __future__ import annotations

import json
import os
import shutil
from dataclasses import asdict

from .schema import CandidateEnv

_REPORT_ADDENDUM = """
--- Output format requirement (machine-graded) ---
Alongside your deliverable(s), write a `report.json` in your output directory with
exactly these top-level keys, each set to the plain number (or value) your analysis
supports — no prose, no nesting, no units in the value:

{keys}

Your work is graded programmatically from `report.json` and the deliverable files.
A key that is missing, renamed, wrapped in a container, or given as prose scores zero.
"""

_TASK_PY = '''"""Auto-generated by wb2gdpval rlgen — do not edit by hand.

Programmatically-rewarded RL environment. Run:

    inspect eval task.py --model <model>
"""

import json
import os

from inspect_ai import Task, task
from inspect_ai.dataset import Sample
from inspect_ai.scorer import Score, Target, mean, scorer
from inspect_ai.solver import TaskState, basic_agent, system_message
from inspect_ai.tool import bash, python
from inspect_ai.util import sandbox

HERE = os.path.dirname(os.path.abspath(__file__))
ENV = json.load(open(os.path.join(HERE, "env.json")))
CHECKS = json.load(open(os.path.join(HERE, "checks.json")))

OUTPUT_DIR = "/task/output"


def _reported_value(report, key):
    """Accept a direct value or the {'reported_value': ..., 'location': ...} form."""
    v = report.get(key)
    if isinstance(v, dict):
        return v.get("reported_value")
    return v


@scorer(metrics=[mean()])
def programmatic_checks():
    async def score(state: TaskState, target: Target) -> Score:
        try:
            raw = await sandbox().read_file(os.path.join(OUTPUT_DIR, "report.json"))
            report = json.loads(raw)
        except Exception:
            report = {}
        total = 0.0
        earned = 0.0
        detail = []
        for c in CHECKS:
            w = float(c.get("weight", 1.0))
            total += w
            ok = False
            if c["check_type"] == "file_exists":
                res = await sandbox().exec(
                    ["test", "-f", os.path.join(OUTPUT_DIR, c["key"])]
                )
                ok = res.returncode == 0
                detail.append(f"{c['key']}: exists={ok}")
            elif c["check_type"] == "json_value":
                v = _reported_value(report, c["key"])
                expected = c.get("expected")
                if isinstance(expected, (int, float)) and not isinstance(expected, bool):
                    try:
                        ok = abs(float(v) - float(expected)) <= float(c.get("tolerance", 0.0))
                    except (TypeError, ValueError):
                        ok = False
                else:
                    ok = v == expected
                detail.append(f"{c['key']}: reported={v!r} expected={expected!r} ok={ok}")
            if ok:
                earned += w
        value = earned / total if total else 0.0
        return Score(value=value, explanation="\\n".join(detail))

    return score


@task
def rl_env() -> Task:
    files = {}
    refroot = os.path.join(HERE, "references")
    for root, _, names in os.walk(refroot):
        for name in names:
            p = os.path.join(root, name)
            rel = os.path.relpath(p, refroot)
            files[os.path.join("/task/reference", rel)] = p
    return Task(
        dataset=[Sample(input=ENV["prompt_with_addendum"], files=files)],
        solver=basic_agent(
            init=system_message(
                "You are completing a professional analysis task. Work in /task; the "
                "reference files are in /task/reference. Write every deliverable and "
                "report.json to /task/output."
            ),
            tools=[bash(timeout=300), python(timeout=300)],
            max_messages=120,
        ),
        scorer=programmatic_checks(),
        sandbox=("docker", os.path.join(HERE, "compose.yaml")),
    )
'''

_DOCKERFILE = """FROM python:3.12-slim
RUN pip install --no-cache-dir \\
    python-docx \\
    python-pptx \\
    openpyxl \\
    pandas \\
    markdown
WORKDIR /task
RUN mkdir -p /task/reference /task/output
"""

_COMPOSE = """services:
  default:
    build: .
    working_dir: /task
    command: tail -f /dev/null
    init: true
"""


def export_env(candidate: CandidateEnv, refdir: str, envs_root: str) -> str:
    """Write one validated candidate as an inspect_ai task directory.

    Refuses candidates that have not passed validation — the exporter is the
    enforcement point for "generate, then validate".
    """
    if not candidate.validation or not candidate.validation.get("valid"):
        raise ValueError(
            f"candidate {candidate.env_id} has not passed validation; "
            "run the validate stage first"
        )
    dest = os.path.join(envs_root, candidate.env_id)
    if os.path.exists(dest):
        shutil.rmtree(dest)
    os.makedirs(dest)

    refs_out = os.path.join(dest, "references")
    for root, _, names in os.walk(refdir):
        for name in names:
            if name.startswith("._") or name == ".DS_Store":
                continue
            p = os.path.join(root, name)
            rel = os.path.relpath(p, refdir)
            dst = os.path.join(refs_out, rel)
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(p, dst)

    json_keys = [c.key for c in candidate.checks if c.check_type == "json_value"]
    addendum = _REPORT_ADDENDUM.format(keys="\n".join(f"- `{k}`" for k in json_keys))
    env_record = candidate.to_dict()
    env_record["prompt_with_addendum"] = candidate.prompt + "\n" + addendum

    with open(os.path.join(dest, "env.json"), "w") as f:
        json.dump(env_record, f, indent=1)
    with open(os.path.join(dest, "checks.json"), "w") as f:
        json.dump([asdict(c) for c in candidate.checks], f, indent=1)
    with open(os.path.join(dest, "task.py"), "w") as f:
        f.write(_TASK_PY)
    with open(os.path.join(dest, "Dockerfile"), "w") as f:
        f.write(_DOCKERFILE)
    with open(os.path.join(dest, "compose.yaml"), "w") as f:
        f.write(_COMPOSE)
    return dest
